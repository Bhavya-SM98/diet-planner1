import React, { useState, useEffect } from 'react';
import axios from 'axios';
import toast from 'react-hot-toast';
import { Salad, Sparkles, Clock } from 'lucide-react';

export default function DietPlan() {
  const [plans, setPlans] = useState([]);
  const [loading, setLoading] = useState(false);
  const [selected, setSelected] = useState(null);

  useEffect(() => { fetchPlans(); }, []);

  const fetchPlans = async () => {
    try {
      const res = await axios.get('/api/user/diet-plans');
      setPlans(res.data);
      if (res.data.length > 0) setSelected(res.data[0]);
    } catch {}
  };

  const generatePlan = async () => {
    setLoading(true);
    try {
      const res = await axios.post('/api/user/diet-plan');
      toast.success('New diet plan generated! 🎉');
      await fetchPlans();
      setSelected({ planContent: res.data.planContent, weekStart: res.data.weekStart });
    } catch (err) {
      toast.error(err.response?.data?.error || 'Failed to generate plan. Please complete your profile first.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      <div className="flex items-center justify-between flex-wrap gap-4">
        <div>
          <h1 className="text-2xl font-bold text-gray-800 flex items-center gap-2"><Salad size={24} className="text-green-500" /> AI Diet Plan</h1>
          <p className="text-gray-500 text-sm mt-1">Personalized weekly meal plans generated by AI</p>
        </div>
        <button onClick={generatePlan} disabled={loading}
          className="flex items-center gap-2 px-5 py-3 bg-gradient-to-r from-green-500 to-emerald-600 text-white font-semibold rounded-xl hover:from-green-600 hover:to-emerald-700 transition-all shadow-md disabled:opacity-60">
          {loading ? <><div className="animate-spin rounded-full h-4 w-4 border-b-2 border-white" /> Generating...</>
            : <><Sparkles size={18} /> Generate New Plan</>}
        </button>
      </div>

      {plans.length > 1 && (
        <div className="flex gap-2 overflow-x-auto pb-2">
          {plans.map((p, i) => (
            <button key={p.id} onClick={() => setSelected(p)}
              className={`flex-shrink-0 flex items-center gap-2 px-4 py-2 rounded-xl text-sm font-medium transition-all ${selected?.id === p.id ? 'bg-green-500 text-white' : 'bg-white text-gray-600 border border-gray-200 hover:border-green-300'}`}>
              <Clock size={14} /> {p.weekStart || `Plan ${plans.length - i}`}
            </button>
          ))}
        </div>
      )}

      {selected ? (
        <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-6">
          <div className="prose max-w-none">
            <pre className="whitespace-pre-wrap font-sans text-sm text-gray-700 leading-relaxed">{selected.planContent}</pre>
          </div>
        </div>
      ) : (
        <div className="bg-white rounded-2xl shadow-sm border border-gray-100 p-16 text-center">
          <div className="text-6xl mb-4">🥗</div>
          <h3 className="font-semibold text-gray-800 mb-2">No diet plan yet</h3>
          <p className="text-gray-400 text-sm mb-6">Complete your profile and click "Generate New Plan" to get a personalized AI diet plan</p>
          <button onClick={generatePlan} disabled={loading}
            className="px-6 py-3 bg-gradient-to-r from-green-500 to-emerald-600 text-white font-semibold rounded-xl hover:from-green-600 hover:to-emerald-700 transition-all shadow-md disabled:opacity-60">
            {loading ? 'Generating...' : '✨ Generate My Plan'}
          </button>
        </div>
      )}
    </div>
  );
}
